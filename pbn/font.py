def text_width(s: str, h: float) -> float:
    return h * (GLYPH_W * len(s) + GAP * (len(s) - 1))


def text(s: str, cx: float, cy: float, h: float) -> list[list[tuple[float, float]]]:
    """Polylines for string s centred on (cx, cy), height h (y up)."""
    missing = set(s) - set(GLYPHS)
    assert not missing, f"no glyph for {sorted(missing)} – add it to GLYPHS in font.py"
    x0, y0 = cx - text_width(s, h) / 2, cy - h / 2
    out = []
    for i, ch in enumerate(s):
        dx = x0 + i * h * (GLYPH_W + GAP)
        out += [[(dx + x * h, y0 + y * h) for x, y in stroke] for stroke in GLYPHS[ch]]
    return out


